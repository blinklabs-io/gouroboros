	rcSeat0Proof     = "a9885aca30b3b895f2d791a3b1579298fedfb53785e37937028fb52a670b7458db0096d537c58007dbd108e56b6aef12"
	rcSeat1PublicKey = "93e02b6052719f607dacd3a088274f65596bd0d09920b61ab5da61bbdc7f5049334cf11213945d57e5ac7d055d042b7e024aa2b2f08f0a91260805272dc51051c6e47ad4fa403b02b4510b647ae3d1770bac0326a805bbefd48056c8c121bdb8"
	rcSeat1Proof     = "9586b1f346f7f0f281d1588d0209cc9815b95722166dcbfa34da8bdb1f78772d72df1f1abed50d27e0246fd0e70b5b21"
	rcSeatStake      = 1_050_000_000_000
