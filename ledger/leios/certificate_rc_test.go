func rcBlock(t *testing.T, name string) *dijkstra.DijkstraBlock {
	t.Helper()
	data, err := os.ReadFile("testdata/" + name)
	require.NoError(t, err)
	raw, err := hex.DecodeString(strings.TrimSpace(string(data)))
	require.NoError(t, err)
	block, err := dijkstra.NewDijkstraBlockFromCbor(raw)
	require.NoError(t, err)
	return block
}

func rcKey(t *testing.T, publicKey, proof string) *common.LeiosKey {
	t.Helper()
	pub, err := hex.DecodeString(publicKey)
	require.NoError(t, err)
	pop, err := hex.DecodeString(proof)
	require.NoError(t, err)
	return &common.LeiosKey{PublicKey: pub, PossessionProof: pop}
}

func TestVerifyPossessionProofRcPrototypeKeys(t *testing.T) {
	t.Parallel()
	require.NoError(t, leios.VerifyPossessionProof(*rcKey(t, rcSeat0PublicKey, rcSeat0Proof)))
	require.NoError(t, leios.VerifyPossessionProof(*rcKey(t, rcSeat1PublicKey, rcSeat1Proof)))
}

func TestVerifyDijkstraCertificateRcPrototypeCertificate(t *testing.T) {
	t.Parallel()

	announcing := rcBlock(t, "rc-2026w41-announcing-block.hex")
	certifying := rcBlock(t, "rc-2026w41-certifying-block.hex")
	require.Equal(t, announcing.Hash(), certifying.PrevHash())
	certified, _ := certifying.BlockHeader.LeiosCertified()
	require.True(t, certified)
	cert := certifying.BlockBody.LeiosCertificate
	require.NotNil(t, cert)
	require.Equal(t, []byte{0xc0}, cert.Signers)

	context := common.DijkstraLeiosCertificateContext{
		AnnouncingBlockHash: announcing.Hash(),
		TotalActiveStake:    2 * rcSeatStake,
		Committee: []common.DijkstraLeiosCommitteeMember{
			{Stake: rcSeatStake, Key: rcKey(t, rcSeat0PublicKey, rcSeat0Proof)},
			{Stake: rcSeatStake, Key: rcKey(t, rcSeat1PublicKey, rcSeat1Proof)},
		},
	}
	quorum := big.NewRat(3, 4)
	require.NoError(t, leios.VerifyDijkstraCertificate(
		cert.Signers, cert.AggregatedSignature, 2, quorum, context,
	))

	// The signature covers the announcing block's hash.
	wrongBlock := context
	wrongBlock.AnnouncingBlockHash = certifying.Hash()
	require.ErrorIs(t, leios.VerifyDijkstraCertificate(
		cert.Signers, cert.AggregatedSignature, 2, quorum, wrongBlock,
	), leios.ErrInvalidSignature)

	// Both seats signed; one seat's stake alone misses the quorum.
	require.ErrorIs(t, leios.VerifyDijkstraCertificate(
		[]byte{0x80}, cert.AggregatedSignature, 2, quorum, context,
	), leios.ErrInsufficientQuorum)
}
